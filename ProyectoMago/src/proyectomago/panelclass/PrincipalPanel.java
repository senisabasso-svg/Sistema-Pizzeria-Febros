    public void cargaProductos(conection conn, MenuPrecios producto) {
        // SQL para obtener el último id de la tabla
        String selectSql = "SELECT MAX(id) FROM menuPrecios";
        // SQL para insertar el nuevo producto
        String insertSql = "INSERT INTO menuPrecios (id, nombre, precio) VALUES (?, ?, ?)";

        try (Connection connection = conn.getConnection(); PreparedStatement selectStmt = conn.prepareStatement(connection, selectSql); ResultSet rs = selectStmt.executeQuery()) {

            int nuevoId = 1;  // Valor predeterminado si la tabla está vacía
            if (rs.next()) {
                nuevoId = rs.getInt(1) + 1;  // Obtener el último id y sumarle 1
            }

            // Preparar la sentencia para insertar el producto
            try (PreparedStatement insertStmt = conn.prepareStatement(connection, insertSql)) {
                // Establecer los valores de los parámetros
                insertStmt.setInt(1, nuevoId); // El nuevo id calculado
                insertStmt.setString(2, producto.getNombre()); // Para el valor de 'nombre'
                insertStmt.setInt(3, producto.getPrecio()); // Para el valor de 'precio'

                // Ejecutar la sentencia INSERT
                int filasAfectadas = insertStmt.executeUpdate();
                System.out.println("Filas afectadas: " + filasAfectadas); // Imprime cuántas filas fueron insertadas
            }

        } catch (SQLException e) {
            System.out.println("Error al cargar productos: " + e.getMessage());
        }
    }

