// Método para buscar un producto por su nombre en la base de datos
    private boolean buscarProductoPorNombre(conection conn, MenuPrecios producto) {
        // Asegúrate de obtener la conexión correctamente, como en tu método cargoMenu
        String query = "SELECT id, nombre, precio FROM menuPrecios WHERE nombre = ?"; // Ajusta el nombre de la tabla a la correcta

        try (Connection connection = conn.getConnection(); // Obtén la conexión usando el método getConnection de conection
                 PreparedStatement stmt = connection.prepareStatement(query)) {

            stmt.setString(1, producto.getNombre());  // Establecer el nombre del producto en el PreparedStatement
            try (ResultSet rs = stmt.executeQuery()) {
                if (rs.next()) {
                    // Si el producto se encuentra, obtenemos los datos y lo asignamos al objeto MenuPrecios
                    producto.setId(rs.getInt("id"));
                    producto.setPrecio(rs.getInt("precio"));
                    return true;  // Producto encontrado
                }
            }
        } catch (SQLException e) {
            // Manejo de excepciones SQL, por ejemplo, loguear el error o mostrarlo
            e.printStackTrace();
        }
        return false;  // Producto no encontrado
    }

