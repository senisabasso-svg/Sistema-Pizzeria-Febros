    private void jButton1ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton1ActionPerformed
        JOptionPane.showMessageDialog(this, "Orden enviada", "Confirmación", JOptionPane.INFORMATION_MESSAGE);
        conection conn = new conection();
        Date dateInforme = new Date();
        Boolean informeDiario = sumoInformeDiario(conn, dateInforme);
        double total = 0.0;
        StringBuilder productosDetalle = new StringBuilder();
        for (Pedido pedido : listaPedidos) {
            double precio = Double.parseDouble(pedido.getPrecio());
            total += precio;
            productosDetalle.append("PRODUCTO : ").append(pedido.getNombreProd())
                    .append(" - PRECIO : $").append(String.format("%.2f", precio))
                    .append("\n");
        }

        try {
            PrintService[] printServices = PrintServiceLookup.lookupPrintServices(null, null);
            PrintService posPrinter = null;

            for (PrintService printService : printServices) {
                if (printService.getName().contains("POS-80C")) {
                    posPrinter = printService;
                    break;
                }
            }

            if (posPrinter == null) {
                throw new Exception("Impresora POS-80C no encontrada");
            }

            // Comando de corte ESC/POS
            byte[] cortarPapel = new byte[]{0x1D, 'V', 1};

            // Crear flujo de impresión
            ByteArrayOutputStream outputStream = new ByteArrayOutputStream();

            // TICKET 1
            String ticket = "";
            ticket += "------------------TICKET 1---------------------\n\n";
            ticket += "               GARAJE GOURMET        \n\n\n";
            ticket += "               TICKET DE VENTA     \n\n\n";
            ticket += productosDetalle.toString();
            ticket += "\n";
            ticket += "               Cantidad: " + listaPedidos.size() + "\n\n";
            ticket += "               Total: $" + String.format("%.2f", total) + "\n\n";
            ticket += "           Gracias por su compra \n\n\n\n";
            outputStream.write(ticket.getBytes("UTF-8"));

            // --- CORTE ACA ---
            outputStream.write("\n\n\n".getBytes());
            outputStream.write(cortarPapel);

            // TICKET 2
            String ticket2 = "";
            ticket2 += "------------------TICKET 2---------------------\n";
            ticket2 += ticket;
            outputStream.write(ticket2.getBytes("UTF-8"));

            // --- CORTE ACA ---
            outputStream.write("\n\n\n".getBytes());
            outputStream.write(cortarPapel);

            // TICKET 3
            String ticket3 = "";
            ticket3 += "------------------TICKET 3---------------------\n";
            ticket3 += ticket;
            outputStream.write(ticket3.getBytes("UTF-8"));

            // CORTE FINAL
            outputStream.write("\n\n\n".getBytes());
            outputStream.write(cortarPapel);

            // Crear y enviar impresión
            DocPrintJob printJob = posPrinter.createPrintJob();
            Doc doc = new SimpleDoc(outputStream.toByteArray(), DocFlavor.BYTE_ARRAY.AUTOSENSE, null);
            printJob.print(doc, null);
            informeDiario = sumoInformeDiario(conn, dateInforme);
            if (informeDiario = true) {
                añadirInformeExistente(conn, dateInforme, precioGlobal);
                listaPedidos.clear();
            } else {
                sumoInforme(conn, dateInforme, precioGlobal); // Imprimir el ticket sin dirección pero con adenda
                JOptionPane.showMessageDialog(this, "Impresión enviada con cortes", "Confirmación", JOptionPane.INFORMATION_MESSAGE);
            }
        } catch (Exception e) {
            JOptionPane.showMessageDialog(this, "Error al imprimir: " + e.getMessage(), "Error", JOptionPane.ERROR_MESSAGE);
            e.printStackTrace();
        }


    }//GEN-LAST:event_jButton1ActionPerformed

